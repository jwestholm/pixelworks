import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const path=new URL('.',import.meta.url);
const src=file=>readFileSync(new URL(file,path),'utf8');
const html=src('./index.html'), js=src('./visual-v2.js'),local=src('./local.js'),css=src('./visual-v2.css');
assert.match(html,/data-dock="office"[\s\S]*?data-dock="play"[\s\S]*?data-dock="agents"/);
assert.match(html,/id="deskAlert"[^>]*hidden/);
assert.match(css,/#deskAlert\[hidden\]\{display:none!important\}/);
assert.match(local,/reports\.filter\(r=>!r\.read&&!r\.archived\)/);
let callback;
let clicks=0;
const tabs=[];
const makeButton=name=>({dataset:{dock:name},classList:{toggle(){},contains(){return false}},setAttribute(){},removeAttribute(){}});
const dock={querySelectorAll(){return ['office','play','agents'].map(makeButton)},addEventListener(type,handler){if(type==='click')callback=handler;}};
const play={click(){clicks++;}};
const lookup={'#gameDock':dock,'#playProjectBtn':play,'#dockDialog':{open:false,addEventListener(){}},'#dockDialogContent':{},'#projectSelect':{value:'demo'}};
const doc={querySelector(sel){return lookup[sel]||null;}};
vm.runInNewContext(js,{document:doc,window:{},console});
await callback({target:{closest(){return makeButton('play')}}});
assert.equal(clicks,1,'Play menu should invoke existing real project preview button');
console.log('PASS: Spela directly after Kontor, clicks existing preview, completion notes visible in inbox');
