import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const js=fs.readFileSync(new URL('./local.js',import.meta.url),'utf8');
const css=fs.readFileSync(new URL('./visual-v2.css',import.meta.url),'utf8');
